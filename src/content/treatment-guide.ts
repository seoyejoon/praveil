// "인천광역시 남동구 성말로 10" → "인천 남동구" (지역 검색어로 씀)
export function areaOf(address: string) {
  const [city = "", gu = ""] = address.split(" ");
  return `${city.replace(/(특별자치시|특별자치도|특별시|광역시|도)$/, "")} ${gu}`.trim();
}

// 받침에 맞는 조사: 필러는 / 여드름 · 모공은
export function josa(word: string, withBatchim: string, without: string) {
  const code = word.charCodeAt(word.length - 1) - 0xac00;
  return code >= 0 && code <= 11171 && code % 28 !== 0 ? withBatchim : without;
}

