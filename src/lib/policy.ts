function contactLines(hospital: PolicyHospital, businessName: string) {
  return [
    `상호: ${businessName}`,
    `주소: ${hospital.address || hospital.region || "병원으로 문의해 주세요."}`,
    `전화: ${hospital.phone || "병원으로 문의해 주세요."}`,
  ].join("\n");
}

