/** 세부 시술 (부위). detail 이 있으면 부위별 탭으로 자세히 보여 줌 */
export type TreatmentItem = {
  name: string;
  text: string;
  image?: string;
  /** 영문 작은 제목 */
  en?: string;
  /** 부위 설명 */
  detail?: string;
  /** 사진 아래에 보이는 설명 (AI 설명용 이미지 표시 등) */
  caption?: string;
  /** 시술 포인트 */
  points?: string[];
  /** 이런 분께 권합니다 */
  recommend?: string[];
};

export type Treatment = {
  href: string;
  /** 한 페이지 안에서 바꿔 보는 하위 시술 (예: 스킨부스터 → 리쥬란힐러 · 엑소좀). 각 href 의 원고를 씀 */
  variants?: { href: string; label: string }[];
  /** 위 variants 의 하나 (단독 주소는 없고 부모 페이지 안에서만 보임) */
  variantOf?: string;
  en: string;
  title: string;
  /** 위 사진 설명 한 줄 */
  description: string;
  image: string;
  /** 장비 시술: 첫 화면에 사진 대신 장비 (배경 없는 제품 사진: public/images/equipment/hero) */
  device?: { src: string; name: string; type: string };
  /** 밝은 시술 장면 사진 (왼쪽이 빈 벽인 3:1 가로 사진). 있으면 장비보다 먼저 씀
   */
  scene?: import("@/components/sub/SceneHero").HeroScene;
  /** 본문 첫 큰 문장 (줄마다) */
  headline: string[];
  intro: string;
  photo: string;
  facts: { label: string; value: string }[];
  recommend: string[];
  points: { title: string; text: string }[];
  /** 의료진이 중요한 이유 3가지 (없으면 공통 문구) */
  doctorReasons?: { title: string; text: string }[];
  /** 세부 시술 섹션 제목 (없으면 "○○ 세부 시술") */
  itemsTitle?: string;
  /** 위 제목 위의 영문 (없으면 부위 목록은 By Area, 그 외는 Program) */
  itemsEn?: string;
  /** 통합 페이지의 세부 시술 */
  items?: TreatmentItem[];
  faq: { q: string; a: string }[];
  cautions: string[];
};

